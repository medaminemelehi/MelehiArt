const I18n = (() => {
  const LANGS = ['en', 'fr'];
  const KEY = 'melehi-lang';
  const ATTRS = ['placeholder', 'aria-label', 'alt', 'title'];
  // Containers that script.js renders itself (translated through t())
  const SKIP = '#paintings-grid, #ceramics-grid, #featured-works, #lightbox-caption, #lightbox-counter, #form-status, #paintings-count, #ceramics-count, #press-grid, #home-press, #press-count, #cf-submit, script, style, svg';
  const originalText = new WeakMap();
  let lang = 'en';

  const norm = s => s.replace(/\s+/g, ' ').trim();
  const tr = en => (lang === 'fr' && FR[norm(en)]) || null;

  function detect() {
    const q = new URLSearchParams(location.search).get('lang');
    if (LANGS.includes(q)) return q;
    try { const saved = localStorage.getItem(KEY); if (LANGS.includes(saved)) return saved; } catch (e) {}
    for (const l of navigator.languages || [navigator.language || '']) {
      const code = String(l).slice(0, 2).toLowerCase();
      if (LANGS.includes(code)) return code;
    }
    return 'en';
  }

  function translateText(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: n => (!n.nodeValue.trim() || n.parentElement.closest(SKIP)) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
    });
    for (let n; (n = walker.nextNode());) {
      if (!originalText.has(n)) originalText.set(n, n.nodeValue);
      const en = originalText.get(n);
      const fr = tr(en);
      // keep the surrounding spaces so inline text still flows
      n.nodeValue = fr ? en.match(/^\s*/)[0] + fr + (/[’']$/.test(fr) ? '' : en.match(/\s*$/)[0]) : en;
    }
  }

  function translateAttrs(root) {
    root.querySelectorAll(ATTRS.map(a => `[${a}]`).join(',')).forEach(el => {
      if (el.closest(SKIP)) return;
      ATTRS.forEach(a => {
        if (!el.hasAttribute(a)) return;
        const store = 'en' + a.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
        if (!(store in el.dataset)) el.dataset[store] = el.getAttribute(a);
        el.setAttribute(a, tr(el.dataset[store]) || el.dataset[store]);
      });
    });
  }

  const meta = { title: document.title, desc: document.querySelector('meta[name="description"]')?.content || '' };

  function apply(next, { save = false } = {}) {
    lang = LANGS.includes(next) ? next : 'en';
    if (save) { try { localStorage.setItem(KEY, lang); } catch (e) {} }
    document.documentElement.lang = lang;
    document.title = tr(meta.title) || meta.title;
    const d = document.querySelector('meta[name="description"]');
    if (d) d.content = tr(meta.desc) || meta.desc;
    translateText(document.body);
    translateAttrs(document.body);
    document.querySelectorAll('[data-lang]').forEach(b => {
      const on = b.dataset.lang === lang;
      b.classList.toggle('active', on);
      b.setAttribute('aria-pressed', on);
    });
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }

  document.addEventListener('click', e => {
    const b = e.target.closest('[data-lang]');
    if (b && b.dataset.lang !== lang) apply(b.dataset.lang, { save: true });
  });

  return {
    get lang() { return lang; },
    apply,
    init() { apply(detect()); },
    t(key, ...args) { const v = UI[lang][key] ?? UI.en[key]; return typeof v === 'function' ? v(...args) : v; },
    // Data values from siteData (e.g. "Acrylic on canvas")
    data(s) { return tr(s) || s; },
    // French writes decimals with a comma: 12.5 → 12,5
    num(s) { return lang === 'fr' ? String(s).replace(/(\d)\.(\d)/g, '$1,$2') : s; }
  };
})();

